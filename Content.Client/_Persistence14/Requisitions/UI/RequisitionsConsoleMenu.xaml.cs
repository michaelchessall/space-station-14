    public RequisitionsConsoleMenu()
    {
        RobustXamlLoader.Load(this);

        _entMan = IoCManager.Resolve<IEntityManager>();
        _proto = IoCManager.Resolve<IPrototypeManager>();
        _materialStorage = _entMan.System<SharedMaterialStorageSystem>();
