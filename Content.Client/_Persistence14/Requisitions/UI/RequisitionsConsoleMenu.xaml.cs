    private void RebuildCart()
    {
        CartContainer.RemoveAllChildren();

        if (_cart.Count == 0)
        {
            CartContainer.AddChild(new Label
            {
                Text = Loc.GetString("requisitions-cart-empty"),
                StyleClasses = { "LabelSubText" },
                Margin = new Thickness(4),
            });
            RebuildTotals();
            return;
        }

        for (var i = 0; i < _cart.Count; i++)
        {
            var index = i;
            var item = _cart[i];
            var entry = _state.Catalogue.FirstOrDefault(e => e.Id == item.Id);
            if (entry == null)
                continue;

            var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };

            // Header row: [icon | name | cost] click to expand, then flatpack checkbox + remove.
            var header = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };

            var expand = new ContainerButton { HorizontalExpand = true };
            var hb = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
            hb.AddChild(new Label { Text = _expanded.Contains(index) ? "▾" : "▸", Margin = new Thickness(0, 0, 4, 0) });
            hb.AddChild(MakeIcon(entry.Result, 28));
            hb.AddChild(new Label { Text = entry.Name, HorizontalExpand = true, Margin = new Thickness(6, 0, 0, 0), ClipText = true });
            hb.AddChild(new Label { Text = $"${ItemCost(entry, item.Flatpack)}", StyleClasses = { "LabelKeyText" } });
            expand.AddChild(hb);
            expand.OnPressed += _ =>
            {
                if (!_expanded.Add(index))
                    _expanded.Remove(index);
                RebuildCart();
            };
            header.AddChild(expand);

            if (entry.Flatpackable)
            {
                var check = new CheckBox { Text = Loc.GetString("requisitions-flatpack"), Pressed = item.Flatpack, Margin = new Thickness(8, 0, 0, 0) };
                check.OnToggled += a =>
                {
                    var it = _cart[index];
                    it.Flatpack = a.Pressed;
                    _cart[index] = it;
                    RebuildCart();
                };
                header.AddChild(check);
            }

            var remove = new Button { Text = "✕", Margin = new Thickness(8, 0, 0, 0), StyleClasses = { "ButtonColorRed" } };
            remove.OnPressed += _ =>
            {
                _cart.RemoveAt(index);
                _expanded.Clear();
                CartChanged();
            };
            header.AddChild(remove);
            box.AddChild(header);

            if (_expanded.Contains(index))
                box.AddChild(BuildCartDetail(entry, item));

            CartContainer.AddChild(box);
        }

        RebuildTotals();
    }

    private Control BuildCartDetail(RequisitionCatalogueEntry entry, RequisitionCartItem item)
    {
        var detail = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(34, 2, 4, 6) };
        var mult = item.Flatpack ? _state.FlatpackMultiplier : 1f;

        if (entry.FromFridge)
        {
            // No materials — just the manual unit price.
            var line = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
            line.AddChild(new Label { Text = Loc.GetString("requisitions-fridge-unit-price"), HorizontalExpand = true, Margin = new Thickness(4, 0, 0, 0), StyleClasses = { "LabelSubText" } });
            line.AddChild(new Label { Text = $"${entry.FridgeUnitPrice}", StyleClasses = { "LabelSubText" } });
            detail.AddChild(line);
        }

        foreach (var (mat, baseAmount) in entry.Materials.OrderBy(kv => kv.Key))
        {
            var raw = (int) MathF.Ceiling(baseAmount * mult);
            var line = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
            line.AddChild(MakeMaterialIcon(mat, 18));
            line.AddChild(new Label { Text = MatLine(mat, raw), HorizontalExpand = true, Margin = new Thickness(4, 0, 0, 0), StyleClasses = { "LabelSubText" } });
            line.AddChild(new Label { Text = $"${SheetCost(mat, raw)}", StyleClasses = { "LabelSubText" } });
            detail.AddChild(line);
        }

        var worth = ItemWorth(entry, item.Flatpack);
        foreach (var fee in FeesFor(entry.Id, entry.Source, item.Flatpack))
        {
            // For a percent fee show the rate and what it works out to on this item, e.g. "Research Fee (10%)".
            var label = fee.Type == RequisitionFeeType.Percent ? $"{fee.Name} ({fee.Price}%)" : fee.Name;
            var line = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
            line.AddChild(new Label { Text = label, HorizontalExpand = true, StyleClasses = { "LabelSubText" } });
            line.AddChild(new Label { Text = $"${fee.AmountFor(worth, 1)}", StyleClasses = { "LabelSubText" } });
            detail.AddChild(line);
        }

        return detail;
    }

    private void RebuildTotals()
    {
        BreakdownContainer.RemoveAllChildren();

        var need = new Dictionary<string, int>();
        // Per-material cost, accumulated one line at a time (each line rounded once).
        var matValue = new Dictionary<string, int>();
        var fridgeLines = new Dictionary<string, (string Name, int Qty, int Total)>();
        var feeAgg = new Dictionary<string, (string Name, bool Percent, int Rate, int Count, int Total)>();
        foreach (var item in _cart)
        {
            var entry = _state.Catalogue.FirstOrDefault(e => e.Id == item.Id);
            if (entry == null)
                continue;

            var qty = Math.Max(1, item.Quantity);
            var worth = 0;
            if (entry.FromFridge)
            {
                // Fridge items have no materials; their worth is the manual unit price.
                worth = entry.FridgeUnitPrice * qty;
                var prevF = fridgeLines.GetValueOrDefault(item.Id);
                fridgeLines[item.Id] = (entry.Name, prevF.Qty + qty, prevF.Total + worth);
            }
            else
            {
                var mult = item.Flatpack ? _state.FlatpackMultiplier : 1f;
                foreach (var (mat, baseAmount) in entry.Materials)
                {
                    var raw = RequisitionCosting.PerUnitRaw(baseAmount, mult) * qty;
                    need[mat] = need.GetValueOrDefault(mat) + raw;
                    var lineCost = SheetCost(mat, raw);
                    worth += lineCost;
                    matValue[mat] = matValue.GetValueOrDefault(mat) + lineCost;
                }
            }

            foreach (var fee in FeesFor(item.Id, item.Source, item.Flatpack))
            {
                var prev = feeAgg.GetValueOrDefault(fee.Id);
                feeAgg[fee.Id] = (fee.Name, fee.Type == RequisitionFeeType.Percent, fee.Price, prev.Count + qty, prev.Total + fee.AmountFor(worth, qty));
            }
        }

        // Stock readout (silo-derived), decremented by cart usage.
        StockContainer.RemoveAllChildren();
        if (_state.Stock.Count == 0)
        {
            StockContainer.AddChild(new Label { Text = Loc.GetString("requisitions-stock-none"), StyleClasses = { "LabelSubText" } });
        }
        else
        {
            foreach (var (mat, have) in _state.Stock.OrderBy(kv => kv.Key))
            {
                var used = need.GetValueOrDefault(mat);
                var cell = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true, Margin = new Thickness(0, 0, 10, 0) };
                cell.AddChild(MakeMaterialIcon(mat, 18));
                var text = MatLine(mat, have - used);
                if (used > 0)
                    text += "  " + Loc.GetString("requisitions-stock-used", ("used", SheetOnly(mat, used)));
                cell.AddChild(new Label { Text = text, HorizontalExpand = true, Margin = new Thickness(4, 0, 0, 0), StyleClasses = { "LabelSubText" }, ClipText = true });
                StockContainer.AddChild(cell);
            }
        }

        var red = Color.FromHex("#e03b3b");
        var materialTotal = 0;
        var anyShort = false;
        foreach (var (mat, qty) in need.OrderBy(kv => kv.Key))
        {
            // The customer's inserted sheets cover part of the need, lowering the billed amount. The base value is
            // the per-line-rounded sum (matValue); the cover discount is applied at the material level.
            var cover = Math.Min(_state.Contributed.GetValueOrDefault(mat), qty);
            var cost = Math.Max(0, matValue.GetValueOrDefault(mat) - SheetCost(mat, cover));
            materialTotal += cost;

            // Short when what the silo must still supply exceeds its stock. Add silo materials, or have the
            // customer contribute more, and it clears.
            var isShort = qty - cover > _state.Stock.GetValueOrDefault(mat);
            if (isShort)
                anyShort = true;

            var text = MatLine(mat, qty);
            if (cover > 0)
                text += "  (−" + MatLine(mat, cover) + ")";

            var line = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
            line.AddChild(MakeMaterialIcon(mat, 18));
            var nameLabel = new Label { Text = text, HorizontalExpand = true, Margin = new Thickness(4, 0, 0, 0) };
            var costLabel = new Label { Text = $"${cost}" };
            if (isShort)
            {
                nameLabel.FontColorOverride = red;
                costLabel.FontColorOverride = red;
            }
            line.AddChild(nameLabel);
            line.AddChild(costLabel);
            BreakdownContainer.AddChild(line);
        }

        // Fridge goods have no material breakdown — list them by name at their manual price.
        var fridgeTotal = 0;
        foreach (var (_, fl) in fridgeLines.OrderBy(kv => kv.Value.Name))
        {
            fridgeTotal += fl.Total;
            var text = fl.Qty > 1 ? $"{fl.Name} ×{fl.Qty}" : fl.Name;
            var line = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
            line.AddChild(new Label { Text = text, HorizontalExpand = true, FontColorOverride = FridgeColor });
            line.AddChild(new Label { Text = $"${fl.Total}" });
            BreakdownContainer.AddChild(line);
        }

        var feeTotal = 0;
        foreach (var (_, fee) in feeAgg)
        {
            feeTotal += fee.Total;
            // Both read "Name (amount) (count)": percent shows the rate, flat shows the per-unit charge.
            var rate = fee.Percent ? $"{fee.Rate}%" : $"${fee.Rate}";
            var text = $"{fee.Name} ({rate}) ({fee.Count})";
            var line = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
            line.AddChild(new Label { Text = text, HorizontalExpand = true, Margin = new Thickness(22, 0, 0, 0) });
            line.AddChild(new Label { Text = $"${fee.Total}" });
            BreakdownContainer.AddChild(line);
        }

        // "Material cost" summary covers all goods (raw materials + fridge items); fees are shown separately.
        var goodsTotal = materialTotal + fridgeTotal;
        var total = goodsTotal + feeTotal;

        // Sync the editable final-price field to the calculated total, but ONLY when that total actually changed.
        // RebuildTotals runs on every state refresh, including background ones that don't touch the price (ejecting
        // stored boards, toggling the detailed-invoice flag, a second viewer opening the console). Comparing against
        // the last total means those refreshes leave a manually-typed price alone, while anything that genuinely
        // alters the price (cart edit, flatpack toggle, a contributed-material or fee/price change) snaps the field
        // back to the fresh calculated figure — discarding the manual edit, as intended.
        if (total != _calculatedTotal)
        {
            _calculatedTotal = total;
            FinalPriceEdit.Text = total.ToString();
        }

        // Locked while a checkout is printing, matching the rest of the tab.
        FinalPriceEdit.Editable = !_state.Processing;

        // Divider, then Material cost / Fees on the left and the Total on the right. Material cost turns red
        // while the silo can't cover the order.
        BreakdownContainer.AddChild(new PanelContainer { StyleClasses = { "LowDivider" }, Margin = new Thickness(0, 4, 0, 4) });
        var summary = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
        var matSummary = new Label
        {
            Text = Loc.GetString("requisitions-summary-material") + $" ${goodsTotal}",
            StyleClasses = { "LabelSubText" },
        };
        if (anyShort)
            matSummary.FontColorOverride = red;
        summary.AddChild(matSummary);
        summary.AddChild(new Label
        {
            Text = "    " + Loc.GetString("requisitions-summary-fees") + $" ${feeTotal}",
            StyleClasses = { "LabelSubText" },
        });
        summary.AddChild(new Control { HorizontalExpand = true });
        summary.AddChild(new Label
        {
            Text = Loc.GetString("requisitions-summary-total") + $" ${total}",
            StyleClasses = { "LabelKeyText" },
        });
        BreakdownContainer.AddChild(summary);

        CheckoutButton.Disabled = _state.Processing || _cart.Count == 0;
        PreviewInvoiceButton.Disabled = _state.Processing || _cart.Count == 0;
        CancelButton.Disabled = _state.Processing;
    }

    private void Checkout()
    {
        // Only treat the field as an override when it's a valid price that differs from the calculated total.
        int? overridePrice = null;
        if (int.TryParse(FinalPriceEdit.Text, out var p) && p >= 0 && p != _calculatedTotal)
            overridePrice = p;

        OnCheckout?.Invoke(new List<RequisitionCartItem>(_cart), PrintInvoiceCheck.Pressed, InvoiceTitle.Text, overridePrice);
        _cart.Clear();
        _expanded.Clear();
        CartChanged();
    }

    private void Preview()
    {
        // Print the invoice this cart would generate without ordering anything, so the cart is left intact.
        int? overridePrice = null;
        if (int.TryParse(FinalPriceEdit.Text, out var p) && p >= 0 && p != _calculatedTotal)
            overridePrice = p;

        OnPreviewInvoice?.Invoke(new List<RequisitionCartItem>(_cart), InvoiceTitle.Text, overridePrice);
    }

