    private Control MakeIcon(string? result, float size = 32)
    {
        var rect = (TextureRect) MakeTextureRect(size);
        if (result != null)
            rect.Texture = _sprite.Frame0(new SpriteSpecifier.EntityPrototype(result));
        return rect;
    }

    private Control MakeMaterialIcon(string matId, float size = 20)
    {
        var rect = (TextureRect) MakeTextureRect(size);
        if (_proto.TryIndex<MaterialPrototype>(matId, out var mat) && mat.StackEntity is { } stack)
            rect.Texture = _sprite.Frame0(new SpriteSpecifier.EntityPrototype(stack));
        return rect;
    }

